#!/usr/bin/env node
// Bash 策略单一源生成器。
//
// 权威数据在 `apps/desktop/contracts/bash-policy.json`；本脚本生成 TS 与 Rust 两侧
// 的常量文件。运行时不再各自维护一份逐字字符串——`generate:bash-policy:check`
// 在 `npm run check` 中强制生成物与契约一致。
//
//   npm run generate:bash-policy          # 重算并写回
//   npm run generate:bash-policy:check    # 仅校验，漂移即非零退出

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const CONTRACT_PATH = path.join(root, 'apps/desktop/contracts/bash-policy.json')
const TS_PATH = path.join(root, 'apps/desktop/src/agent/tools/bashPolicy.generated.ts')
const RUST_PATH = path.join(root, 'apps/desktop/src-tauri/src/bash_policy_generated.rs')
const checkOnly = process.argv.includes('--check')

const fail = (message) => {
  console.error(`generate-bash-policy: ${message}`)
  process.exit(1)
}

const policy = JSON.parse(readFileSync(CONTRACT_PATH, 'utf8'))
const requiredKeys = [
  'maxTimeoutMs',
  'maxCommandBytes',
  'maxOutputBytes',
  'defaultShell',
  'sudoCommandPrefixPattern',
  'outsideWorkspaceRedirectPattern',
  'networkKeywords',
]
const actualKeys = Object.keys(policy).sort()
if (JSON.stringify(actualKeys) !== JSON.stringify([...requiredKeys].sort())) {
  fail(`contract keys drifted: ${actualKeys.join(', ')}`)
}
for (const key of ['maxTimeoutMs', 'maxCommandBytes', 'maxOutputBytes']) {
  if (!Number.isSafeInteger(policy[key]) || policy[key] <= 0) fail(`${key} must be a positive safe integer`)
}
if (typeof policy.defaultShell !== 'string' || !policy.defaultShell.startsWith('/')) {
  fail('defaultShell must be an absolute path')
}
for (const key of ['sudoCommandPrefixPattern', 'outsideWorkspaceRedirectPattern']) {
  if (typeof policy[key] !== 'string' || policy[key].length === 0) fail(`${key} must be a non-empty string`)
  if (policy[key].includes('`') || policy[key].includes('${')) {
    fail(`${key} must not contain backtick or template interpolation (TS String.raw constraint)`)
  }
  if (policy[key].includes('"')) {
    fail(`${key} must not contain double quotes (Rust raw-string constraint)`)
  }
  try {
    new RegExp(policy[key])
  } catch (error) {
    fail(`${key} is not a valid JavaScript RegExp: ${error.message}`)
  }
}
if (!Array.isArray(policy.networkKeywords) || policy.networkKeywords.length === 0) {
  fail('networkKeywords must be a non-empty array')
}
const seen = new Set()
for (const keyword of policy.networkKeywords) {
  if (typeof keyword !== 'string' || keyword.length === 0) fail('networkKeywords entries must be non-empty strings')
  if (keyword.includes('"') || keyword.includes('\\')) fail(`networkKeywords entry must not contain quote/backslash: ${keyword}`)
  if (seen.has(keyword)) fail(`duplicate network keyword: ${keyword}`)
  seen.add(keyword)
}

const tsSource = `// AUTO-GENERATED by scripts/generate-bash-policy.mjs — do not edit by hand.
// Source of truth: apps/desktop/contracts/bash-policy.json
export const BASH_POLICY = {
  maxTimeoutMs: ${policy.maxTimeoutMs},
  maxCommandBytes: ${policy.maxCommandBytes},
  maxOutputBytes: ${policy.maxOutputBytes},
  defaultShell: '${policy.defaultShell}',
  sudoCommandPrefixPattern: String.raw\`${policy.sudoCommandPrefixPattern}\`,
  outsideWorkspaceRedirectPattern: String.raw\`${policy.outsideWorkspaceRedirectPattern}\`,
  networkKeywords: [
${policy.networkKeywords.map((keyword) => `    '${keyword}',`).join('\n')}
  ],
} as const
`

const rustSource = `// AUTO-GENERATED by scripts/generate-bash-policy.mjs — do not edit by hand.
// Source of truth: apps/desktop/contracts/bash-policy.json
#![allow(dead_code)]

pub(crate) const MAX_TIMEOUT_MS: u64 = ${policy.maxTimeoutMs};
pub(crate) const MAX_COMMAND_BYTES: usize = ${policy.maxCommandBytes};
pub(crate) const MAX_OUTPUT_BYTES: usize = ${policy.maxOutputBytes};
#[cfg_attr(not(unix), allow(dead_code))]
pub(crate) const DEFAULT_SHELL: &str = "${policy.defaultShell}";
pub(crate) const SUDO_COMMAND_PREFIX_PATTERN: &str = r"${policy.sudoCommandPrefixPattern}";
pub(crate) const OUTSIDE_WORKSPACE_REDIRECT_PATTERN: &str = r"${policy.outsideWorkspaceRedirectPattern}";
pub(crate) const NETWORK_KEYWORDS: &[&str] = &[
${policy.networkKeywords.map((keyword) => `    "${keyword}",`).join('\n')}
];
`

const outputs = [
  [TS_PATH, tsSource],
  [RUST_PATH, rustSource],
]
const drifted = []
for (const [file, content] of outputs) {
  let current = ''
  try {
    current = readFileSync(file, 'utf8')
  } catch {
    current = ''
  }
  if (current !== content) drifted.push(file)
}

if (checkOnly) {
  if (drifted.length === 0) {
    console.log('bash policy generation check passed: TS/Rust constants match contracts/bash-policy.json.')
    process.exit(0)
  }
  console.error(`bash policy generated files are stale (${drifted.length}):`)
  for (const file of drifted) console.error(`  ${path.relative(root, file)}`)
  console.error('运行 `npm run generate:bash-policy` 重算并写回。')
  process.exit(1)
}

if (drifted.length === 0) {
  console.log('bash policy generated files are already in sync — no changes written.')
  process.exit(0)
}
for (const file of drifted) {
  const content = outputs.find(([target]) => target === file)[1]
  writeFileSync(file, content)
}
console.log(`updated ${drifted.length} bash policy generated file(s):`)
for (const file of drifted) console.log(`  ${path.relative(root, file)}`)
